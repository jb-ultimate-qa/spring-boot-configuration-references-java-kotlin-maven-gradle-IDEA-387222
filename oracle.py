#!/usr/bin/env python3
"""Runtime oracle for IDEA-387222 (temp.md, section 5.6).

Usage: python -I oracle.py [ROOT]    ROOT defaults to the directory of this script.

1. Runs the tests of every project: `gradlew test`, `mvn -q test`.
2. Starts the application class on its production classpath. It must fail on the
   key that exists only in src/test/resources.
3. Runs probe/RuntimeProbe.java on the production and test classpaths of each module:
   which config files Spring Boot loads, and where every key comes from.

Writes the output to ROOT/runtime-oracle.txt and copies it into every project root.
Needs JAVA_HOME (JDK 21) and mvn on the PATH. Never runs the integrationTest task.
"""
import glob, os, re, shutil, subprocess, sys
import xml.etree.ElementTree as ET

root = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else os.path.dirname(os.path.abspath(__file__)))
GRADLE = os.path.join(root, "gradle-project")
MAVEN = os.path.join(root, "maven-project")
SINGLE = os.path.join(root, "maven-single-module")
PROBE = os.path.join(root, "probe")
java = os.path.join(os.environ["JAVA_HOME"], "bin", "java")
javac = os.path.join(os.environ["JAVA_HOME"], "bin", "javac")
gradlew = os.path.join(GRADLE, "gradlew.bat" if os.name == "nt" else "gradlew")
mvn = shutil.which("mvn")
root_url = "file:/" + root.replace("\\", "/").lstrip("/") + "/"

KEYS = ["my.property", "main.only.property", "main.url", "yaml.property", "yaml.main-only",
        "test.only.property", "test.url", "yaml.test-only", "imported.test.property",
        "extra.key", "lib.test.only", "integration.only.property"]
SINGLE_KEYS = ["my.key", "foo"]

out = []
def log(text=""):
    text = text.replace(root_url, "").replace(root + os.sep, "")
    print(text)
    out.append(text)

def run(cmd):
    p = subprocess.run(cmd, cwd=root, capture_output=True, text=True, encoding="utf-8", errors="replace", timeout=900)
    return p.returncode, p.stdout + p.stderr

def junit(pattern):
    for path in sorted(glob.glob(pattern)):
        suite = ET.parse(path).getroot()
        failed = int(suite.get("failures", 0)) + int(suite.get("errors", 0))
        detail = " ".join((e.get("message") or "") + " " + (e.text or "")
                          for e in suite.iter() if e.tag in ("failure", "error"))
        cause = re.search(r"Could not resolve placeholder '[^']*'|failure threshold \(\d+\) exceeded", detail)
        log(f"  {suite.get('name')}: {'FAIL' if failed else 'PASS'}" + (f" ({cause.group(0)})" if cause else ""))

def read_cp(path):
    with open(path, encoding="utf-8") as f:
        return f.read().strip()

log("# IDEA-387222 runtime oracle (generated by oracle.py; paths relative to the qa root)")
code, text = run([java, "-version"])
log("# " + text.splitlines()[0])

log("\n== 1. Tests ==")
code, _ = run([gradlew, "-p", GRADLE, "test", "--continue", "-q"])
log(f"gradle-project: gradlew test -> exit {code}")
junit(os.path.join(GRADLE, "*", "build", "test-results", "test", "TEST-*.xml"))
for project, reports in ((MAVEN, os.path.join(MAVEN, "*", "target", "surefire-reports", "TEST-*.xml")),
                         (SINGLE, os.path.join(SINGLE, "target", "surefire-reports", "TEST-*.xml"))):
    code, _ = run([mvn, "-q", "test", "-f", os.path.join(project, "pom.xml")])
    log(f"{os.path.basename(project)}: mvn -q test -> exit {code}")
    junit(reports)

# Classpaths. Gradle: an init script. Maven: dependency:build-classpath in the reactor.
code, text = run([gradlew, "-p", GRADLE, "-I", os.path.join(PROBE, "classpath.init.gradle"), "qaClasspaths", "-q"])
if code:
    sys.exit("qaClasspaths failed:\n" + text)
def gradle_cp(module, source_set):
    return read_cp(os.path.join(GRADLE, module, "build", "qa", f"classpath-{source_set}.txt"))
for project in (MAVEN, SINGLE):
    for scope in ("runtime", "test"):
        code, text = run([mvn, "-q", "-f", os.path.join(project, "pom.xml"), "test-compile", "dependency:build-classpath",
                          "-Dmdep.includeScope=" + scope, "-Dmdep.outputFile=target/qa-classpath-" + scope + ".txt"])
        if code:
            sys.exit("dependency:build-classpath failed:\n" + text)
def maven_cp(module_dir, scope):
    deps = read_cp(os.path.join(module_dir, "target", f"qa-classpath-{scope}.txt"))
    dirs = [os.path.join(module_dir, "target", "classes")]
    if scope == "test":
        dirs.insert(0, os.path.join(module_dir, "target", "test-classes"))
    return os.pathsep.join(dirs + [deps])

log("\n== 2. Application class on the production classpath ==")
for label, cp, main in (("gradle-project app", gradle_cp("app", "main"), "demo.MainApplication"),
                        ("maven-project app", maven_cp(os.path.join(MAVEN, "app"), "runtime"), "demo.MainApplication"),
                        ("maven-single-module", maven_cp(SINGLE, "runtime"), "demo.single.SingleApplication")):
    code, text = run([java, "-cp", cp, main])
    cause = re.search(r"Could not resolve placeholder '[^']*' in value \"[^\"]*\"", text)
    log(f"{label}: {main} -> exit {code}: {cause.group(0) if cause else 'no placeholder failure'}")

log("\n== 3. RuntimeProbe ==")
classes = os.path.join(PROBE, "classes")
code, text = run([javac, "-d", classes, "-cp", gradle_cp("app", "test"), os.path.join(PROBE, "RuntimeProbe.java")])
if code:
    sys.exit("javac failed:\n" + text)
PROBES = [
    ("P1", "gradle-project app, production", gradle_cp("app", "main"), "-", KEYS),
    ("P2", "gradle-project app, production, profile test", gradle_cp("app", "main"), "test", KEYS),
    ("P3", "gradle-project app, test", gradle_cp("app", "test"), "-", KEYS),
    ("P4", "gradle-project app, test, profile test", gradle_cp("app", "test"), "test", KEYS),
    ("P5", "gradle-project app, integrationTest", gradle_cp("app", "integrationTest"), "-", KEYS),
    ("P6", "gradle-project lib, test", gradle_cp("lib", "test"), "-", KEYS),
    ("P7", "maven-project app, production", maven_cp(os.path.join(MAVEN, "app"), "runtime"), "-", KEYS),
    ("P8", "maven-project app, production, profile test", maven_cp(os.path.join(MAVEN, "app"), "runtime"), "test", KEYS),
    ("P9", "maven-project app, test", maven_cp(os.path.join(MAVEN, "app"), "test"), "-", KEYS),
    ("P10", "maven-project app, test, profile test", maven_cp(os.path.join(MAVEN, "app"), "test"), "test", KEYS),
    ("P11", "maven-project lib, test", maven_cp(os.path.join(MAVEN, "lib"), "test"), "-", KEYS),
    ("P12", "maven-single-module, production", maven_cp(SINGLE, "runtime"), "-", SINGLE_KEYS),
    ("P13", "maven-single-module, test", maven_cp(SINGLE, "test"), "-", SINGLE_KEYS),
]
for pid, label, cp, profiles, keys in PROBES:
    code, text = run([java, "-Dlogging.level.root=WARN", "-cp", classes + os.pathsep + cp, "RuntimeProbe", profiles] + keys)
    log(f"\n--- {pid}: {label} (exit {code}) ---")
    for line in text.splitlines():
        log(line)

with open(os.path.join(root, "runtime-oracle.txt"), "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(out) + "\n")
for project in (GRADLE, MAVEN, SINGLE):
    shutil.copyfile(os.path.join(root, "runtime-oracle.txt"), os.path.join(project, "runtime-oracle.txt"))
